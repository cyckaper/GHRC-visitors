/**
 * 測試裡的日期照台北時間的「現在」往後推，不寫死。
 *
 * 主場次（西澳大學，`<日期>-uwa`）在兩套測試裡都要一直是「接下來那一場」：後台打開停在今天或之後
 * 最近的那一場、來賓專頁照日期分訪前／當天／訪後的措辭、確認信標「現在該寄」、支援人力表不收已經結束的場次。
 * 以前寫死 2026-10-07，那一天一過這幾項就全部對不上，每個 PR 都紅——跟那個 PR 改了什麼無關。
 *
 * 規矩：要「接下來那一場」就用 `taipeiDate(往後幾天)`；要已經過去的，用遠在過去的固定日期（2020-01-01）；
 * 要一直在將來、又不在乎是哪一天的，用 2099。**不要寫死一個「現在還在將來」的日期。**
 *
 * 「今天」跟後台、來賓專頁、伺服器（`netlify/lib/http.mts taipeiToday`）是同一個算法：
 * 台北沒有夏令時間，加八小時之後取 UTC 的日期與時間，就是台北的日期與時間。
 */

/** 某一刻在台北是哪一天、幾點幾分：`{ date: "YYYY-MM-DD", time: "HH:MM" }`。 */
export function taipei(ms = Date.now()) {
  const iso = new Date(ms + 8 * 3600e3).toISOString();
  return { date: iso.slice(0, 10), time: iso.slice(11, 16) };
}

/**
 * 台北時間今天往後 `days` 天（YYYY-MM-DD）。主場次至少往後兩天：測試跑到一半跨過台北的午夜，
 * 「明天」就變成「今天」，來賓專頁的訪前措辭會變成當天的。
 */
export const taipeiDate = (days = 0) => taipei(Date.now() + days * 86400e3).date;
